def _canonicalize(raw: str) -> Optional[str]:
    """Turn a POSIX-ish locale string into a bare ``lang`` or ``lang_REGION`` token.

    Strips encoding (``.UTF-8``) and modifier (``@euro``) suffixes, e.g.
    ``"pt_BR.UTF-8"`` -> ``"pt_BR"``, ``"zh_CN"`` -> ``"zh_CN"``.
    """
    if not raw:
        return None
    value = raw.strip()
    if not value or value.lower() in ("c", "posix"):
        return None
    value = value.split(".")[0].split("@")[0]
    return value or None


def normalize_language(value: Optional[str]) -> Optional[str]:
    """Map an arbitrary locale-ish string to one of :data:`SUPPORTED_LANGUAGES`.

    Accepts things like ``"es"``, ``"es_ES"``, ``"es-ES.UTF-8"``,
    ``"zh_Hans"``, ``"zh_CN"``, ``"pt_BR"``. Returns ``None`` if ``value``
    is empty or doesn't map to a supported locale.
    """
    canonical = _canonicalize(value) if isinstance(value, str) else None
    if not canonical:
        return None

    token = canonical.replace("-", "_")
    parts = token.split("_")
    lang = parts[0].lower()

    # Chinese: only Simplified is bundled, so every Chinese variant
    # (zh, zh_CN, zh_Hans, zh_SG, zh_TW, zh_Hant, ...) maps to zh-Hans —
    # a deliberate simplification rather than shipping no Chinese at all.
    if lang == "zh":
        return "zh-Hans"

    if lang in SUPPORTED_LANGUAGES:
        return lang

    return None


def resolve_system_language() -> str:
    """Detect a supported language from the environment, defaulting to English.

    Checks ``LC_ALL``, ``LC_MESSAGES`` and ``LANG`` in that order (the
    standard glibc precedence for message-catalog selection), then falls
    back to :func:`locale.getlocale`. Returns :data:`DEFAULT_LANGUAGE`
    (English — not Spanish) if nothing usable is found.
    """
    for var in ("LC_ALL", "LC_MESSAGES", "LANG"):
        normalized = normalize_language(os.environ.get(var))
        if normalized:
            return normalized

    try:
        detected, _ = locale.getlocale()
    except (ValueError, TypeError):
        detected = None
    normalized = normalize_language(detected)
    if normalized:
        return normalized

    return DEFAULT_LANGUAGE


def t(key: str, language: Optional[str] = None, **kwargs: object) -> str:
    """Translate ``key`` for ``language``, falling back to English then the raw key.

    Missing languages/keys never raise: an unsupported ``language`` or an
    unknown ``key`` silently falls back, since a translation gap must never
    crash the on-device UI.
    """
    bundle = TRANSLATIONS.get(language or "", {})
    text = bundle.get(key)
    if text is None:
        text = TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError):
            return text
    return text
